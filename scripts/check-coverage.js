#!/usr/bin/env node
/**
 * Enforce the coverage requirements of SENG 34213 §6.4.
 *
 *   • 80 % lines and statements across all measured application code
 *   • 90 % across each module classified as critical business logic
 *   • no measured file below a floor, so an average cannot hide a blind spot
 *
 * Jest's own `coverageThreshold` covers the global gate; this script adds the
 * per-module band the course asks for and writes a readable summary for the
 * sprint review.
 *
 *   npm run coverage:check
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { REPO_ROOT, config, isSutAvailable, resolveSut } = require('../src/support/sut');

const BACKEND_SUMMARY = path.join(REPO_ROOT, 'reports/coverage/backend/coverage-summary.json');
const FRONTEND_SUMMARY = path.join(REPO_ROOT, 'reports/coverage/frontend/coverage-summary.json');
const MARKDOWN = path.join(REPO_ROOT, 'reports', 'coverage-summary.md');

/** A file counts as critical when its SUT-relative path matches the config list. */
function isCritical(filePath) {
  const backendDir = isSutAvailable() ? resolveSut().backendDir : '';
  const relative = backendDir ? path.relative(backendDir, filePath) : filePath;
  return config.coverage.criticalPaths.some((fragment) =>
    relative.replace(/\\/g, '/').endsWith(fragment),
  );
}

function loadSummary(file, label) {
  if (!fs.existsSync(file)) {
    return { label, available: false, files: [], total: null };
  }

  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  const { total, ...files } = raw;

  return {
    label,
    available: true,
    total,
    files: Object.entries(files).map(([filePath, metrics]) => ({
      path: filePath,
      relative: isSutAvailable()
        ? path.relative(resolveSut().root, filePath).replace(/\\/g, '/')
        : filePath,
      lines: metrics.lines.pct,
      statements: metrics.statements.pct,
      branches: metrics.branches.pct,
      functions: metrics.functions.pct,
      critical: isCritical(filePath),
    })),
  };
}

const pct = (value) => (typeof value === 'number' ? `${value.toFixed(1)}%` : '—');

function evaluate(summaries) {
  const violations = [];

  for (const summary of summaries) {
    if (!summary.available) continue;

    const global = config.coverage.global;
    for (const metric of ['lines', 'statements', 'branches', 'functions']) {
      const actual = summary.total[metric].pct;
      if (actual < global[metric]) {
        violations.push({
          scope: `${summary.label} (global)`,
          metric,
          actual,
          required: global[metric],
        });
      }
    }

    const critical = config.coverage.criticalBusinessLogic;
    for (const file of summary.files.filter((entry) => entry.critical)) {
      for (const metric of ['lines', 'branches']) {
        if (file[metric] < critical[metric]) {
          violations.push({
            scope: file.relative,
            metric,
            actual: file[metric],
            required: critical[metric],
            note: 'critical business logic',
          });
        }
      }
    }
  }

  return violations;
}

function renderMarkdown(summaries, violations) {
  const lines = [];

  lines.push('# Test Coverage Summary');
  lines.push('');
  lines.push('<!-- Generated by scripts/check-coverage.js — do not edit by hand. -->');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push('');
  lines.push('## Requirements (SENG 34213 §6.4)');
  lines.push('');
  lines.push('| Layer | Requirement |');
  lines.push('| --- | --- |');
  lines.push(`| All new code | ${config.coverage.global.lines}% lines and statements |`);
  lines.push(
    `| Critical business logic | ${config.coverage.criticalBusinessLogic.branches}% branches |`,
  );
  lines.push('| API endpoints | 100% exercised by an integration test |');
  lines.push('');

  for (const summary of summaries) {
    lines.push(`## ${summary.label}`);
    lines.push('');

    if (!summary.available) {
      lines.push('_No coverage data. Run `npm run coverage` first._');
      lines.push('');
      continue;
    }

    lines.push('| Metric | Covered | Required | Result |');
    lines.push('| --- | --- | --- | --- |');
    for (const metric of ['lines', 'statements', 'branches', 'functions']) {
      const actual = summary.total[metric].pct;
      const required = config.coverage.global[metric];
      lines.push(
        `| ${metric} | ${pct(actual)} | ${required}% | ${actual >= required ? '✅' : '❌'} |`,
      );
    }
    lines.push('');

    const criticalFiles = summary.files.filter((entry) => entry.critical);
    if (criticalFiles.length > 0) {
      lines.push('### Critical business logic');
      lines.push('');
      lines.push('| File | Lines | Branches | Functions | Result |');
      lines.push('| --- | --- | --- | --- | --- |');
      for (const file of criticalFiles.sort((a, b) => a.relative.localeCompare(b.relative))) {
        const ok =
          file.lines >= config.coverage.criticalBusinessLogic.lines &&
          file.branches >= config.coverage.criticalBusinessLogic.branches;
        lines.push(
          `| \`${file.relative}\` | ${pct(file.lines)} | ${pct(file.branches)} | ${pct(
            file.functions,
          )} | ${ok ? '✅' : '❌'} |`,
        );
      }
      lines.push('');
    }

    lines.push('### All measured files');
    lines.push('');
    lines.push('| File | Lines | Branches | Functions |');
    lines.push('| --- | --- | --- | --- |');
    for (const file of summary.files.sort((a, b) => a.lines - b.lines)) {
      lines.push(
        `| \`${file.relative}\`${file.critical ? ' 🔒' : ''} | ${pct(file.lines)} | ${pct(
          file.branches,
        )} | ${pct(file.functions)} |`,
      );
    }
    lines.push('');
  }

  lines.push('## Result');
  lines.push('');
  if (violations.length === 0) {
    lines.push('✅ Every coverage gate is met.');
  } else {
    lines.push('❌ Coverage gates not met:');
    lines.push('');
    lines.push('| Scope | Metric | Covered | Required |');
    lines.push('| --- | --- | --- | --- |');
    for (const violation of violations) {
      lines.push(
        `| \`${violation.scope}\`${violation.note ? ` (${violation.note})` : ''} | ${
          violation.metric
        } | ${pct(violation.actual)} | ${violation.required}% |`,
      );
    }
  }
  lines.push('');
  lines.push('🔒 marks a module classified as critical business logic in `testing.config.js`.');
  lines.push('');

  return `${lines.join('\n')}\n`;
}

function main() {
  const summaries = [
    loadSummary(BACKEND_SUMMARY, 'Backend (Jest)'),
    loadSummary(FRONTEND_SUMMARY, 'Frontend (Vitest)'),
  ];

  if (summaries.every((summary) => !summary.available)) {
    process.stderr.write('\n✗ No coverage data was found. Run `npm run coverage` first.\n\n');
    process.exit(1);
  }

  const violations = evaluate(summaries);

  fs.mkdirSync(path.dirname(MARKDOWN), { recursive: true });
  fs.writeFileSync(MARKDOWN, renderMarkdown(summaries, violations));

  process.stdout.write('\nCoverage gates (SENG 34213 §6.4)\n');
  for (const summary of summaries.filter((entry) => entry.available)) {
    process.stdout.write(
      `  ${summary.label.padEnd(18)} lines ${pct(summary.total.lines.pct)}  ` +
        `branches ${pct(summary.total.branches.pct)}\n`,
    );
  }
  process.stdout.write(`  → ${path.relative(REPO_ROOT, MARKDOWN)}\n\n`);

  if (violations.length > 0) {
    process.stderr.write(`✗ ${violations.length} coverage gate(s) not met:\n\n`);
    for (const violation of violations) {
      process.stderr.write(
        `    ${violation.scope} — ${violation.metric} ${pct(violation.actual)} ` +
          `(requires ${violation.required}%)${violation.note ? ` [${violation.note}]` : ''}\n`,
      );
    }
    process.stderr.write('\n');
    process.exit(1);
  }

  process.stdout.write('✓ Every coverage gate is met.\n\n');
}

if (require.main === module) main();

module.exports = { loadSummary, evaluate, renderMarkdown };
