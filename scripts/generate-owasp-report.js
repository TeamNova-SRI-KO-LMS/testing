#!/usr/bin/env node
/**
 * Render the OWASP Top 10 compliance evidence required by SENG 34213 §8.1 and
 * submitted as deliverable §10.1 #8.
 *
 * The control matrix lives in `src/registry/owasp.js`; this script joins it
 * against the executed test register so each claim is backed by a test case
 * that actually ran, with its real outcome. A control that cites a test case
 * which no longer exists is reported as unevidenced rather than quietly
 * accepted — the failure mode that makes most compliance documents worthless.
 *
 *   npm run report:owasp
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { REPO_ROOT } = require('../src/support/sut');
const controls = require('../src/registry/owasp');

const REGISTER = path.join(REPO_ROOT, 'reports', 'test-register.json');
const MARKDOWN = path.join(REPO_ROOT, 'docs', 'security', 'OWASP_COMPLIANCE.md');
const JSON_OUT = path.join(REPO_ROOT, 'reports', 'owasp-compliance.json');

const cell = (value) =>
  String(value ?? '—')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

function loadRegister() {
  if (!fs.existsSync(REGISTER)) {
    process.stderr.write(
      '\n✗ reports/test-register.json is missing.\n' +
        '  Run `npm test && npm run report:register` first — the OWASP evidence is\n' +
        '  generated from cases that actually executed, not from the matrix alone.\n\n',
    );
    process.exit(1);
  }
  const parsed = JSON.parse(fs.readFileSync(REGISTER, 'utf8'));
  return new Map((parsed.cases || []).map((entry) => [entry.id, entry]));
}

function build() {
  const register = loadRegister();

  return controls.map((control) => {
    const evidence = control.cases.map((id) => {
      const entry = register.get(id);
      return {
        id,
        found: Boolean(entry),
        name: entry?.name ?? null,
        type: entry?.type ?? null,
        status: entry?.status ?? 'NOT FOUND IN REGISTER',
        knownDefect: Boolean(entry?.knownDefect),
        defect: entry?.defect ?? null,
        file: entry?.file ?? null,
      };
    });

    const missing = evidence.filter((entry) => !entry.found);
    const passing = evidence.filter((entry) => entry.status === 'Pass');
    const documentedGaps = evidence.filter((entry) => entry.knownDefect);

    return {
      ...control,
      evidence,
      missing,
      counts: {
        total: evidence.length,
        passing: passing.length,
        documentedGaps: documentedGaps.length,
        missing: missing.length,
      },
    };
  });
}

function renderMarkdown(rows) {
  const lines = [];

  lines.push('# OWASP Top 10 Compliance Evidence');
  lines.push('');
  lines.push('<!-- Generated by scripts/generate-owasp-report.js — do not edit by hand. -->');
  lines.push('');
  lines.push(
    'Prepared against the control matrix in SENG 34213 §8.1 and submitted as deliverable ' +
      '§10.1 #8.',
  );
  lines.push('');
  lines.push(
    'Every claim below cites test cases from ' +
      '[TEST_REGISTER.md](../testing/TEST_REGISTER.md), and each citation is checked ' +
      'against the register when this document is generated. A control whose evidence ' +
      'has been deleted or renamed is reported as unevidenced rather than passing quietly.',
  );
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push('');

  lines.push('## Status at a glance');
  lines.push('');
  lines.push('| Risk | Name | Status | Evidence | Open defects |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const row of rows) {
    const badge =
      row.counts.missing > 0
        ? '⚠️ Evidence missing'
        : row.status === 'Compliant'
          ? '✅ Compliant'
          : row.status === 'Automated in CI'
            ? '⚙️ Automated in CI'
            : '🟡 Partial';
    lines.push(
      `| ${row.id} | ${cell(row.name)} | ${badge} | ${
        row.counts.total === 0 ? 'CI pipeline' : `${row.counts.passing}/${row.counts.total} cases`
      } | ${row.defects.length > 0 ? row.defects.join(', ') : '—'} |`,
    );
  }
  lines.push('');
  lines.push(
    '> 🟡 **Partial** means the control is implemented and verified, but at least one ' +
      'gap remains. Each gap is a numbered entry in ' +
      '[DEFECT_REGISTER.md](../testing/DEFECT_REGISTER.md) with a test case that will ' +
      'break the build the moment it is fixed — so the status here cannot silently go ' +
      'stale.',
  );
  lines.push('');

  lines.push('## Controls in detail');
  lines.push('');

  for (const row of rows) {
    lines.push(`### ${row.id} — ${row.name}`);
    lines.push('');
    lines.push(`**Required control (§8.1):** ${row.requirement}`);
    lines.push('');
    lines.push(`**How the application implements it:** ${row.implementation}`);
    lines.push('');
    lines.push(`**Assessment:** ${row.notes}`);
    lines.push('');

    if (row.evidence.length === 0) {
      lines.push('**Evidence:** enforced by the CI pipeline; see the linked workflow run.');
      lines.push('');
    } else {
      lines.push('**Evidence:**');
      lines.push('');
      lines.push('| Test case | Description | Layer | Result |');
      lines.push('| --- | --- | --- | --- |');
      for (const entry of row.evidence) {
        const result = !entry.found
          ? '❌ not found in register'
          : entry.knownDefect
            ? `⚠️ documents ${entry.defect}`
            : entry.status === 'Pass'
              ? '✅ Pass'
              : `❌ ${entry.status}`;
        lines.push(
          `| \`${entry.id}\` | ${cell(entry.name ?? '—')} | ${cell(entry.type ?? '—')} | ${result} |`,
        );
      }
      lines.push('');
    }

    if (row.defects.length > 0) {
      lines.push(`**Open defects:** ${row.defects.join(', ')}`);
      lines.push('');
    }
  }

  lines.push('## How to reproduce this evidence');
  lines.push('');
  lines.push('```bash');
  lines.push('npm run sut:endpoints      # derive the endpoint inventory from the source');
  lines.push('npm run test:unit');
  lines.push('npm run test:integration');
  lines.push('npm run test:security      # the OWASP suite');
  lines.push('npm run report:register    # capture what actually ran');
  lines.push('npm run report:owasp       # regenerate this document');
  lines.push('```');
  lines.push('');

  return `${lines.join('\n')}\n`;
}

function main() {
  const rows = build();

  fs.mkdirSync(path.dirname(MARKDOWN), { recursive: true });
  fs.writeFileSync(MARKDOWN, renderMarkdown(rows));
  fs.writeFileSync(
    JSON_OUT,
    `${JSON.stringify({ generatedAt: new Date().toISOString(), controls: rows }, null, 2)}\n`,
  );

  const unevidenced = rows.filter((row) => row.counts.missing > 0);

  process.stdout.write('\nOWASP Top 10 compliance (SENG 34213 §8.1)\n');
  process.stdout.write(`  Controls          : ${rows.length}\n`);
  process.stdout.write(
    `  Fully compliant   : ${rows.filter((row) => row.status === 'Compliant').length}\n`,
  );
  process.stdout.write(
    `  Partial           : ${rows.filter((row) => row.status === 'Partial').length}\n`,
  );
  process.stdout.write(
    `  CI-enforced       : ${rows.filter((row) => row.status === 'Automated in CI').length}\n`,
  );
  process.stdout.write(`  → ${path.relative(REPO_ROOT, MARKDOWN)}\n\n`);

  if (unevidenced.length > 0) {
    process.stderr.write('✗ Some controls cite test cases that are not in the register:\n\n');
    for (const row of unevidenced) {
      process.stderr.write(
        `    ${row.id}  missing: ${row.missing.map((entry) => entry.id).join(', ')}\n`,
      );
    }
    process.stderr.write(
      '\n  Either the case was renamed or deleted, or src/registry/owasp.js is out of date.\n\n',
    );
    process.exit(1);
  }

  process.stdout.write('✓ Every cited test case exists in the register.\n\n');
}

if (require.main === module) main();

module.exports = { build, renderMarkdown };
