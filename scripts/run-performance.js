#!/usr/bin/env node
/**
 * Run a k6 performance scenario and render the result as a report.
 *
 *   npm run test:perf                    all scenarios except stress
 *   npm run test:perf -- --scenario load one scenario
 *   npm run test:perf -- --all           every scenario, stress included
 *
 * k6 is a Go binary, not an npm package, so this script checks for it and
 * explains how to install it rather than failing with "command not found".
 * Output lands in `reports/performance/` and is summarised into
 * `reports/performance-report.md` for deliverable §10.1 #9.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const { REPO_ROOT, config } = require('../src/support/sut');

const SCENARIO_DIR = path.join(REPO_ROOT, 'tests', 'performance', 'scenarios');
const OUTPUT_DIR = path.join(REPO_ROOT, 'reports', 'performance');
const MARKDOWN = path.join(REPO_ROOT, 'reports', 'performance-report.md');

/** Stress is excluded by default: it is exploratory and takes six minutes. */
const DEFAULT_SCENARIOS = ['smoke', 'load', 'spike'];
const ALL_SCENARIOS = ['smoke', 'load', 'stress', 'spike'];

function parseArguments(argv) {
  const scenarioIndex = argv.indexOf('--scenario');
  if (scenarioIndex !== -1 && argv[scenarioIndex + 1]) {
    return [argv[scenarioIndex + 1]];
  }
  return argv.includes('--all') ? ALL_SCENARIOS : DEFAULT_SCENARIOS;
}

function k6IsInstalled() {
  const probe = spawnSync('k6', ['version'], { encoding: 'utf8' });
  return probe.status === 0;
}

function explainMissingK6() {
  process.stderr.write(
    [
      '',
      '  k6 is not installed.',
      '',
      '  It is a standalone binary rather than an npm package:',
      '',
      '    macOS    brew install k6',
      '    Linux    sudo gpg -k && \\',
      '             sudo gpg --no-default-keyring \\',
      '               --keyring /usr/share/keyrings/k6-archive-keyring.gpg \\',
      '               --keyserver hkp://keyserver.ubuntu.com:80 \\',
      '               --recv-keys C5AD17C747E3415A3642D57D77C6C491D6AC1D69 && \\',
      '             echo "deb [signed-by=/usr/share/keyrings/k6-archive-keyring.gpg] ' +
        'https://dl.k6.io/deb stable main" | sudo tee /etc/apt/sources.list.d/k6.list && \\',
      '             sudo apt-get update && sudo apt-get install k6',
      '    Windows  winget install k6 --source winget',
      '    Docker   docker run --rm -i grafana/k6 run - <tests/performance/scenarios/smoke.js',
      '',
      '  The CI pipeline installs it automatically (.github/workflows/performance.yml).',
      '',
    ].join('\n'),
  );
}

function runScenario(name) {
  const scenarioPath = path.join(SCENARIO_DIR, `${name}.js`);
  if (!fs.existsSync(scenarioPath)) {
    process.stderr.write(
      `\n✗ Unknown scenario "${name}". Available: ${ALL_SCENARIOS.join(', ')}\n\n`,
    );
    process.exit(1);
  }

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const summaryPath = path.join(OUTPUT_DIR, `${name}-summary.json`);

  process.stdout.write(`\n▶ ${name} — target ${config.performance.baseUrl}\n\n`);

  const result = spawnSync(
    'k6',
    ['run', '--summary-export', summaryPath, '--quiet', scenarioPath],
    {
      stdio: 'inherit',
      env: { ...process.env, PERF_BASE_URL: config.performance.baseUrl },
    },
  );

  return { name, summaryPath, exitCode: result.status };
}

/** k6 exits 99 when a threshold is breached but the run itself completed. */
const THRESHOLD_BREACH_EXIT_CODE = 99;

function readSummary(summaryPath) {
  if (!fs.existsSync(summaryPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(summaryPath, 'utf8'));
  } catch {
    return null;
  }
}

function metric(summary, name, field) {
  const value = summary?.metrics?.[name]?.[field];
  return typeof value === 'number' ? Math.round(value * 100) / 100 : null;
}

function renderReport(results) {
  const lines = [];

  lines.push('# Performance Test Results');
  lines.push('');
  lines.push('<!-- Generated by scripts/run-performance.js — do not edit by hand. -->');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`Target: \`${config.performance.baseUrl}\``);
  lines.push('');
  lines.push('## Non-functional targets');
  lines.push('');
  lines.push('| Metric | Target |');
  lines.push('| --- | --- |');
  lines.push(
    `| Request failure rate | < ${config.performance.thresholds.httpReqFailedRate * 100}% |`,
  );
  lines.push(`| Response time p95 | < ${config.performance.thresholds.httpReqDurationP95} ms |`);
  lines.push(`| Response time p99 | < ${config.performance.thresholds.httpReqDurationP99} ms |`);
  lines.push(`| Login p95 | < ${config.performance.thresholds.loginDurationP95} ms |`);
  lines.push('');
  lines.push('## Results by scenario');
  lines.push('');
  lines.push('| Scenario | Requests | Failure rate | p95 (ms) | p99 (ms) | Max (ms) | Result |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');

  for (const result of results) {
    const summary = readSummary(result.summaryPath);
    if (!summary) {
      lines.push(`| ${result.name} | — | — | — | — | — | ⚠️ no summary produced |`);
      continue;
    }

    const requests = metric(summary, 'http_reqs', 'count') ?? 0;
    const failureRate = metric(summary, 'http_req_failed', 'value');
    const verdict =
      result.exitCode === 0
        ? '✅ pass'
        : result.exitCode === THRESHOLD_BREACH_EXIT_CODE
          ? '❌ threshold breached'
          : `❌ exit ${result.exitCode}`;

    lines.push(
      `| ${result.name} | ${requests} | ${
        failureRate === null ? '—' : `${(failureRate * 100).toFixed(2)}%`
      } | ${metric(summary, 'http_req_duration', 'p(95)') ?? '—'} | ${
        metric(summary, 'http_req_duration', 'p(99)') ?? '—'
      } | ${metric(summary, 'http_req_duration', 'max') ?? '—'} | ${verdict} |`,
    );
  }

  lines.push('');
  lines.push('## Interpretation');
  lines.push('');
  lines.push(
    '- **smoke** — one user, ten iterations. Answers "is the system correct and up?" ' +
      'A failure here invalidates every other scenario.',
  );
  lines.push(
    '- **load** — a ramp to 50 concurrent users held for two minutes, mixing anonymous ' +
      'browsing with sign-ins. These are the headline numbers for the report.',
  );
  lines.push(
    '- **stress** — a ramp to 300 users to locate the breaking point. Relaxed thresholds: ' +
      'the output is a capacity figure, not a pass or fail.',
  );
  lines.push(
    '- **spike** — 5 users to 200 in ten seconds, then back. The recovery window at the ' +
      'end is the part that matters: a system that stays degraded after a spike will not ' +
      'survive enrolment day.',
  );
  lines.push('');
  lines.push('Raw k6 summaries: `reports/performance/<scenario>-summary.json`.');
  lines.push('');

  return `${lines.join('\n')}\n`;
}

function main() {
  if (!k6IsInstalled()) {
    explainMissingK6();
    process.exit(1);
  }

  const scenarios = parseArguments(process.argv.slice(2));
  const results = scenarios.map(runScenario);

  fs.mkdirSync(path.dirname(MARKDOWN), { recursive: true });
  fs.writeFileSync(MARKDOWN, renderReport(results));
  process.stdout.write(`\n✓ ${path.relative(REPO_ROOT, MARKDOWN)}\n\n`);

  // A threshold breach fails the build; anything worse fails it louder.
  const worst = results.reduce((code, result) => Math.max(code, result.exitCode || 0), 0);
  process.exit(worst === 0 ? 0 : 1);
}

if (require.main === module) main();

module.exports = { renderReport, parseArguments, ALL_SCENARIOS, DEFAULT_SCENARIOS };
