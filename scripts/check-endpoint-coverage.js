#!/usr/bin/env node
/**
 * Enforce SENG 34213 §6.4: *100 % of API endpoints must have at least one
 * integration test*.
 *
 * Joins two machine-generated inputs:
 *   • reports/endpoint-inventory.json  — every route declared in the
 *                                        application (scripts/extract-endpoints.js)
 *   • reports/.endpoint-hits/*.json    — every request the integration suite
 *                                        actually made (src/support/api-client.js)
 *
 * Writes reports/endpoint-coverage.md and exits non-zero when any endpoint was
 * never exercised, so the CI pipeline fails on an untested route rather than
 * relying on someone remembering to update a checklist.
 *
 *   npm run report:endpoints
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { REPO_ROOT } = require('../src/support/sut');

const INVENTORY = path.join(REPO_ROOT, 'reports', 'endpoint-inventory.json');
const HITS_DIR = path.join(REPO_ROOT, 'reports', '.endpoint-hits');
const MARKDOWN = path.join(REPO_ROOT, 'reports', 'endpoint-coverage.md');
const JSON_OUT = path.join(REPO_ROOT, 'reports', 'endpoint-coverage.json');

/**
 * Turn `/api/courses/:id/enroll` into a matcher, and count its literal
 * segments so a concrete request can be attributed to the most specific route —
 * exactly how Express itself resolves `/api/courses/my-courses` against both
 * `/api/courses/my-courses` and `/api/courses/:id`.
 */
function toMatcher(routePath) {
  const segments = routePath.split('/');
  const literalSegments = segments.filter((s) => s && !s.startsWith(':')).length;
  const pattern = segments
    .map((segment) => {
      if (!segment) return '';
      if (segment.startsWith(':')) return '[^/]+';
      return segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    })
    .join('/');

  return { regex: new RegExp(`^${pattern}/?$`), literalSegments };
}

function loadInventory() {
  if (!fs.existsSync(INVENTORY)) {
    process.stderr.write(
      '\n✗ reports/endpoint-inventory.json is missing. Run `npm run sut:endpoints` first.\n\n',
    );
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(INVENTORY, 'utf8'));
}

function loadHits() {
  if (!fs.existsSync(HITS_DIR)) return [];
  return fs
    .readdirSync(HITS_DIR)
    .filter((file) => file.endsWith('.json'))
    .flatMap((file) => JSON.parse(fs.readFileSync(path.join(HITS_DIR, file), 'utf8')));
}

/** Attribute each recorded request to the most specific matching endpoint. */
function attribute(endpoints, hits) {
  const prepared = endpoints.map((endpoint) => ({
    ...endpoint,
    ...toMatcher(endpoint.path),
    hits: 0,
    statuses: new Set(),
    suites: new Set(),
  }));

  const unmatched = [];

  for (const hit of hits) {
    const candidates = prepared.filter(
      (endpoint) => endpoint.method === hit.method && endpoint.regex.test(hit.path),
    );

    if (candidates.length === 0) {
      unmatched.push(hit);
      continue;
    }

    // Most literal segments wins: the specific route beats the parameterised one.
    const best = candidates.reduce((winner, candidate) =>
      candidate.literalSegments > winner.literalSegments ? candidate : winner,
    );

    best.hits += 1;
    best.statuses.add(hit.status);
    if (hit.suite) best.suites.add(hit.suite);
  }

  return { prepared, unmatched };
}

function renderMarkdown(report) {
  const { summary, groups, uncovered, aliases } = report;
  const lines = [];

  lines.push('# API Endpoint Coverage');
  lines.push('');
  lines.push('<!-- Generated by scripts/check-endpoint-coverage.js — do not edit by hand. -->');
  lines.push('');
  lines.push(`Generated: ${report.generatedAt}`);
  lines.push('');
  lines.push(
    'SENG 34213 §6.4 requires every API endpoint to be exercised by at least one ' +
      'integration test. This report is derived from the application source and ' +
      'from the requests the suite actually made, so it cannot drift out of date.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| Metric | Value |');
  lines.push('| --- | --- |');
  lines.push(`| Endpoints subject to the gate | ${summary.total} |`);
  lines.push(`| Covered | ${summary.covered} |`);
  lines.push(`| Uncovered | ${summary.uncovered} |`);
  lines.push(`| **Coverage** | **${summary.percentage}%** |`);
  lines.push(`| Requirement | 100% |`);
  lines.push(`| Result | ${summary.passed ? '✅ PASS' : '❌ FAIL'} |`);
  lines.push(`| Total requests recorded | ${summary.totalRequests} |`);
  lines.push('');

  if (uncovered.length > 0) {
    lines.push('## Uncovered endpoints');
    lines.push('');
    lines.push('| Method | Path | Access | Declared in |');
    lines.push('| --- | --- | --- | --- |');
    for (const endpoint of uncovered) {
      lines.push(
        `| ${endpoint.method} | \`${endpoint.path}\` | ${endpoint.access} | ${endpoint.source}:${endpoint.line} |`,
      );
    }
    lines.push('');
  }

  lines.push('## Coverage by route group');
  lines.push('');
  lines.push('| Group | Endpoints | Covered | Requests | Coverage |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const group of groups) {
    lines.push(
      `| \`${group.name}\` | ${group.total} | ${group.covered} | ${group.requests} | ${group.percentage}% |`,
    );
  }
  lines.push('');

  lines.push('## Full endpoint register');
  lines.push('');
  lines.push('| Method | Path | Access | Requests | Observed statuses | Status |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const endpoint of report.endpoints) {
    lines.push(
      `| ${endpoint.method} | \`${endpoint.path}\` | ${endpoint.access} | ${endpoint.hits} | ` +
        `${endpoint.statuses.join(', ') || '—'} | ${endpoint.hits > 0 ? '✅' : '❌'} |`,
    );
  }
  lines.push('');

  if (aliases.length > 0) {
    lines.push('## Deployment aliases (excluded from the gate)');
    lines.push('');
    lines.push(
      'The application mounts the admin router and several health routes under a ' +
        'Choreo deployment prefix that rewrites onto the same handlers. They are ' +
        'aliases of routes already covered above; ' +
        '`tests/integration/api/system/choreo-alias.test.js` proves the prefix itself works.',
    );
    lines.push('');
    for (const alias of aliases) {
      lines.push(`- ${alias.method} \`${alias.path}\``);
    }
    lines.push('');
  }

  return `${lines.join('\n')}\n`;
}

function main() {
  const inventory = loadInventory();
  const hits = loadHits();

  const testable = inventory.endpoints.filter((e) => !e.alias && !e.catchAll);
  const { prepared, unmatched } = attribute(testable, hits);

  const covered = prepared.filter((endpoint) => endpoint.hits > 0);
  const uncovered = prepared.filter((endpoint) => endpoint.hits === 0);

  // Group by the router prefix, e.g. /api/courses.
  const groupsByName = new Map();
  for (const endpoint of prepared) {
    const name = endpoint.path.split('/').slice(0, 3).join('/') || '/';
    if (!groupsByName.has(name)) {
      groupsByName.set(name, { name, total: 0, covered: 0, requests: 0 });
    }
    const group = groupsByName.get(name);
    group.total += 1;
    group.requests += endpoint.hits;
    if (endpoint.hits > 0) group.covered += 1;
  }
  const groups = [...groupsByName.values()]
    .map((group) => ({
      ...group,
      percentage: group.total === 0 ? 100 : Math.round((group.covered / group.total) * 100),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

  const percentage =
    prepared.length === 0 ? 0 : Math.round((covered.length / prepared.length) * 1000) / 10;

  const report = {
    generatedAt: new Date().toISOString(),
    summary: {
      total: prepared.length,
      covered: covered.length,
      uncovered: uncovered.length,
      percentage,
      passed: uncovered.length === 0,
      totalRequests: hits.length,
      unmatchedRequests: unmatched.length,
    },
    groups,
    uncovered: uncovered.map(({ method, path: p, access, source, line }) => ({
      method,
      path: p,
      access,
      source,
      line,
    })),
    endpoints: prepared
      .map(({ method, path: p, access, hits: count, statuses, suites }) => ({
        method,
        path: p,
        access,
        hits: count,
        statuses: [...statuses].sort((a, b) => a - b),
        suites: [...suites].sort(),
      }))
      .sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`)),
    aliases: inventory.endpoints
      .filter((e) => e.alias)
      .map(({ method, path: p }) => ({ method, path: p })),
  };

  fs.mkdirSync(path.dirname(MARKDOWN), { recursive: true });
  fs.writeFileSync(JSON_OUT, `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(MARKDOWN, renderMarkdown(report));

  // ---- console summary -------------------------------------------------
  const { summary } = report;
  process.stdout.write('\nAPI endpoint coverage (SENG 34213 §6.4)\n');
  process.stdout.write(`  Endpoints : ${summary.total}\n`);
  process.stdout.write(`  Covered   : ${summary.covered}\n`);
  process.stdout.write(`  Requests  : ${summary.totalRequests}\n`);
  process.stdout.write(`  Coverage  : ${summary.percentage}% (required: 100%)\n`);

  if (summary.unmatchedRequests > 0) {
    // Not a failure: security tests deliberately request paths that do not exist.
    process.stdout.write(
      `  Note      : ${summary.unmatchedRequests} recorded requests matched no declared route\n`,
    );
  }
  process.stdout.write(`  → ${path.relative(REPO_ROOT, MARKDOWN)}\n\n`);

  if (!summary.passed) {
    process.stderr.write(`✗ ${summary.uncovered} endpoint(s) have no integration test:\n\n`);
    for (const endpoint of report.uncovered) {
      process.stderr.write(`    ${endpoint.method.padEnd(6)} ${endpoint.path}\n`);
      process.stderr.write(`           declared in ${endpoint.source}:${endpoint.line}\n`);
    }
    process.stderr.write('\n');
    process.exit(1);
  }

  process.stdout.write('✓ Every API endpoint is exercised by at least one integration test.\n\n');
}

if (require.main === module) main();

module.exports = { toMatcher, attribute };
